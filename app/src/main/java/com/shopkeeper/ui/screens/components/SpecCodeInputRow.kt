/**
 * Progressive disclosure component for product specification & barcode entry.
 * Retailers who do not track custom barcodes or specs keep their form streamlined,
 * while hardware / electrical / grocery retailers can expand and scan effortlessly.
 */
@Composable
fun SpecCodeInputRow(
    code: String,
    onCodeChange: (String) -> Unit,
    modifier: Modifier = Modifier,
    autoGeneratedPlaceholder: String = "1001",
    errorMessage: String? = null,
    onScanBarcodeClick: () -> Unit = {}
) {
    var isExpanded by rememberSaveable(code) {
        mutableStateOf(code.isNotBlank())
    }

    Column(modifier = modifier.fillMaxWidth()) {
        AnimatedVisibility(
            visible = !isExpanded && code.isBlank(),
            enter = fadeIn() + expandVertically(),
            exit = fadeOut() + shrinkVertically()
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(4.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                TextButton(
                    onClick = { isExpanded = true },
                    contentPadding = PaddingValues(horizontal = 8.dp, vertical = 4.dp),
                    colors = ButtonDefaults.textButtonColors(
                        contentColor = MaterialTheme.colorScheme.primary
                    )
                ) {
                    Icon(
                        imageVector = Icons.Default.Add,
                        contentDescription = null,
                        modifier = Modifier.size(16.dp)
                    )
                    Spacer(modifier = Modifier.width(4.dp))
                    Text(
                        text = stringResource(R.string.action_add_spec),
                        fontSize = 13.sp,
                        fontWeight = FontWeight.SemiBold,
                        maxLines = 1,
                        softWrap = false
                    )
                }

                TextButton(
                    onClick = {
                        isExpanded = true
                        onScanBarcodeClick()
                    },
                    contentPadding = PaddingValues(horizontal = 8.dp, vertical = 4.dp),
                    colors = ButtonDefaults.textButtonColors(
                        contentColor = MaterialTheme.colorScheme.secondary
                    )
                ) {
                    Icon(
                        imageVector = Icons.Default.CameraAlt,
                        contentDescription = stringResource(R.string.barcode_scanner_description),
                        modifier = Modifier.size(16.dp)
                    )
                    Spacer(modifier = Modifier.width(4.dp))
                    Text(
                        text = stringResource(R.string.action_scan_barcode),
                        fontSize = 13.sp,
                        fontWeight = FontWeight.SemiBold,
                        maxLines = 1,
                        softWrap = false
                    )
                }
            }
        }

        AnimatedVisibility(
            visible = isExpanded || code.isNotBlank(),
            enter = fadeIn() + expandVertically(),
            exit = fadeOut() + shrinkVertically()
        ) {
            Column(modifier = Modifier.fillMaxWidth()) {
                ShopTextField(
                    value = code,
                    onValueChange = onCodeChange,
                    label = stringResource(R.string.spec_code_label),
                    placeholder = stringResource(R.string.spec_code_placeholder),
                    isError = errorMessage != null,
                    errorMessage = errorMessage,
                    leadingIcon = {
                        Icon(
                            imageVector = Icons.Default.QrCode,
                            contentDescription = null,
                            tint = MaterialTheme.colorScheme.primary,
                            modifier = Modifier.size(20.dp)
                        )
                    },
                    trailingIcon = {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            IconButton(onClick = onScanBarcodeClick) {
                                Icon(
                                    imageVector = Icons.Default.CameraAlt,
                                    contentDescription = stringResource(R.string.action_scan_barcode),
                                    tint = MaterialTheme.colorScheme.primary,
                                    modifier = Modifier.size(20.dp)
                                )
                            }
                            if (code.isBlank()) {
                                IconButton(onClick = { isExpanded = false }) {
                                    Icon(
                                        imageVector = Icons.Default.Close,
                                        contentDescription = stringResource(R.string.action_hide_spec),
                                        tint = MaterialTheme.colorScheme.onSurfaceVariant,
                                        modifier = Modifier.size(18.dp)
                                    )
                                }
                            }
                        }
                    },
                    keyboardOptions = KeyboardOptions(
                        capitalization = KeyboardCapitalization.Characters,
                        imeAction = ImeAction.Next
                    )
                )

                if (code.isBlank() && errorMessage == null) {
                    Text(
                        text = stringResource(R.string.spec_code_auto_hint, autoGeneratedPlaceholder),
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        fontSize = 11.sp,
                        fontWeight = FontWeight.Normal,
                        modifier = Modifier.fillMaxWidth()
                    )
                }
            }
        }
    }
}

